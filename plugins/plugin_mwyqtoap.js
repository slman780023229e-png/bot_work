/**
 * إرجاع التعبير الرمزي الخاص بأي أمر
 * @param {string} commandName - اسم الأمر (مع أو بدون بادئة)
 * @param {string} fallback - الرمز الافتراضي إذا لم يُعثر على الأمر
 * @returns {string}
 */
export function getCommandEmoji(commandName, fallback = '⚡') {
  if (!commandName) return fallback;
  const clean = String(commandName)
    .trim()
    .replace(/^[./!#?~]+/, '')
    .toLowerCase();

  if (COMMAND_EMOJIS[clean]) return COMMAND_EMOJIS[clean];

  const underscored = clean.replace(/\s+/g, '_');
  if (COMMAND_EMOJIS[underscored]) return COMMAND_EMOJIS[underscored];

  return fallback;
}

